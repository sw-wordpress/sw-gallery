#!/usr/bin/env php
<?php

declare(strict_types=1);

/**
 * Generates packages/wordpress/src/Support/CoreMessages.php: every static user-facing message of the framework independent
 * core (typed exception messages) as a literal __() call, so xgettext can extract them into the .pot file and the adapter can
 * translate them at presentation time. Programmer-error exceptions (\InvalidArgumentException, \LogicException) are not
 * user-facing and are not translated. Run through bin/i18n.sh (pot/update).
 */

$root = dirname(__DIR__);
$messages = [];
$iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/packages/core/src/Exception', FilesystemIterator::SKIP_DOTS));
foreach ($iterator as $file) {
    if ($file->getExtension() !== 'php') {
        continue;
    }
    $code = (string) file_get_contents($file->getPathname());
    // parent::__construct('literal') and constructor defaults such as "string $message = 'literal'".
    preg_match_all("/parent::__construct\\(\\s*('(?:[^'\\\\]|\\\\.)*')\\s*[,)]/", $code, $parents);
    preg_match_all("/\\\$message\\s*=\\s*('(?:[^'\\\\]|\\\\.)*')/", $code, $defaults);
    foreach (array_merge($parents[1], $defaults[1]) as $literal) {
        $value = eval('return ' . $literal . ';');
        if (is_string($value) && $value !== '') {
            $messages[$value] = true;
        }
    }
}
$messages = array_keys($messages);
sort($messages);

// Validation messages (FU-09): "new ValidationError(self::ERROR_X, <path>, 'literal' | sprintf('template', ...))". They are
// formatted in English by the core, so the adapter translates them by stable error code: the template list per code is
// generated here, the numbers/types are read back from the English message by the adapter.
$validator = (string) file_get_contents($root . '/packages/core/src/Domain/Settings/SettingsSchemaValidator.php');
preg_match_all("/const\\s+(ERROR_\\w+)\\s*=\\s*'([a-z_]+)'/", $validator, $consts, PREG_SET_ORDER);
$codes = [];
foreach ($consts as $const) {
    $codes[$const[1]] = $const[2];
}
preg_match_all(
    "/new ValidationError\\(\\s*self::(ERROR_\\w+),\\s*[^,]+,\\s*(?:sprintf\\(\\s*)?('(?:[^'\\\\]|\\\\.)*')/s",
    $validator,
    $found,
    PREG_SET_ORDER
);
$templates = [];
foreach ($found as $match) {
    $value = eval('return ' . $match[2] . ';');
    if (!isset($codes[$match[1]]) || !is_string($value) || $value === '') {
        fwrite(STDERR, "Unresolved validation message for {$match[1]}\n");
        exit(1);
    }
    $templates[$codes[$match[1]]][$value] = true;
}
ksort($templates);

$header = <<<'PHP'
<?php
