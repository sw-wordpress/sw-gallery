#!/usr/bin/env php
<?php

declare(strict_types=1);

/**
 * Generates packages/wordpress/src/Support/CoreMessages.php: every static user-facing message of the framework independent
 * core (typed exception messages) as a literal __() call, so xgettext can extract them into the .pot file and the adapter can
 * translate them at presentation time. Programmer-error exceptions (\InvalidArgumentException, \LogicException) are not
 * user-facing and are not translated. Run through bin/i18n.sh (pot/update).
 */

$root = dirname(__DIR__);
$messages = [];
$iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/packages/core/src/Exception', FilesystemIterator::SKIP_DOTS));
foreach ($iterator as $file) {
    if ($file->getExtension() !== 'php') {
        continue;
    }
    $code = (string) file_get_contents($file->getPathname());
    // parent::__construct('literal') and constructor defaults such as "string $message = 'literal'".
    preg_match_all("/parent::__construct\\(\\s*('(?:[^'\\\\]|\\\\.)*')\\s*[,)]/", $code, $parents);
    preg_match_all("/\\\$message\\s*=\\s*('(?:[^'\\\\]|\\\\.)*')/", $code, $defaults);
    foreach (array_merge($parents[1], $defaults[1]) as $literal) {
        $value = eval('return ' . $literal . ';');
        if (is_string($value) && $value !== '') {
            $messages[$value] = true;
        }
    }
}
$messages = array_keys($messages);
sort($messages);

$header = <<<'PHP'
<?php
/**
 * GENERATED by bin/i18n-core-messages.php - do not edit.
 *
 * Static messages of the framework independent core as literal gettext calls so they can be extracted into the
 * .pot file. translate() looks a message up in the active catalog at presentation time (REST errors).
 *
 * @package sw-gallery
 */

declare(strict_types=1);

namespace SWGallery\WordPress\Support;

final class CoreMessages {

	/**
	 * Translates a core message when the catalog knows it; unknown (e.g. dynamic) messages are returned unchanged.
	 *
	 * @param string $message English message produced by the core.
	 */
	public static function translate( string $message ): string {
		// phpcs:ignore WordPress.WP.I18n.NonSingularStringLiteralText -- runtime lookup of catalog entries declared in catalog().
		return __( $message, 'sw-gallery' );
	}

	/**
	 * Declares the translatable core messages (never executed, only scanned by xgettext).
	 *
	 * @return list<string>
	 */
	public static function catalog(): array {
		return array(

PHP;
$out = $header;
foreach ($messages as $message) {
    $out .= "\t\t\t__( " . var_export($message, true) . ", 'sw-gallery' ),\n";
}
$out .= "\t\t);\n\t}\n}\n";
if (!is_dir($root . '/packages/wordpress/src/Support')) {
    mkdir($root . '/packages/wordpress/src/Support', 0775, true);
}
file_put_contents($root . '/packages/wordpress/src/Support/CoreMessages.php', $out);
fwrite(STDOUT, count($messages) . " core messages\n");
